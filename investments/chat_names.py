def new_chat_account_name(reserved_names):
    for _ in range(5000):
        candidate = f"{choice(FIRST_NAMES)} {choice(SURNAMES)}"
        if candidate.casefold() not in reserved_names:
            reserved_names.add(candidate.casefold())
            return candidate
    raise ValueError("تعذر إنشاء اسم عربي فريد للحساب.")
