BASE58_ALPHABET = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz"
USDT_DECIMALS = 6


def _fernet():
    configured_key = getattr(settings, "WALLET_ENCRYPTION_KEY", "")
    if configured_key:
        key = configured_key.encode("ascii")
    elif settings.DEBUG:
        # Keeps local development usable; production must configure a separate secret.
        digest = hmac.new(settings.SECRET_KEY.encode(), b"cinevest-wallet-encryption-v1", hashlib.sha256).digest()
        import base64

        key = base64.urlsafe_b64encode(digest)
    else:
        raise ImproperlyConfigured("Set WALLET_ENCRYPTION_KEY before creating or viewing managed wallets.")
    try:
        return Fernet(key)
    except (TypeError, ValueError) as exc:
        raise ImproperlyConfigured("WALLET_ENCRYPTION_KEY must be a Fernet key generated by Fernet.generate_key().") from exc


def _legacy_development_fernet():
    digest = hmac.new(settings.SECRET_KEY.encode(), b"cinevest-wallet-encryption-v1", hashlib.sha256).digest()
    import base64

    return Fernet(base64.urlsafe_b64encode(digest))


def encrypt_private_key(private_key):
    return _fernet().encrypt(private_key.encode("ascii")).decode("ascii")


def decrypt_private_key(encrypted_private_key):
    token = encrypted_private_key.encode("ascii")
    encryptors = [_fernet()]
    if getattr(settings, "WALLET_ENCRYPTION_KEY", ""):
        encryptors.append(_legacy_development_fernet())
    for encryptor in encryptors:
        try:
            return encryptor.decrypt(token).decode("ascii")
        except (InvalidToken, UnicodeDecodeError):
            continue
    raise ImproperlyConfigured(
        "تعذر فك تشفير المفتاح الخاص. تحقق من ثبات مفاتيح التشفير وDjango SECRET_KEY."
    )


def _base58_encode(value):
    number = int.from_bytes(value, "big")
    encoded = ""
    while number:
        number, remainder = divmod(number, 58)
        encoded = BASE58_ALPHABET[remainder] + encoded
    leading_zeroes = len(value) - len(value.lstrip(b"\0"))
    return ("1" * leading_zeroes) + (encoded or ("" if leading_zeroes else "1"))


def _base58_decode(value):
    number = 0
    for character in value:
        number = number * 58 + BASE58_ALPHABET.index(character)
    body = number.to_bytes((number.bit_length() + 7) // 8, "big") if number else b""
    leading_zeroes = len(value) - len(value.lstrip("1"))
    decoded = (b"\0" * leading_zeroes) + body
    if len(decoded) < 5:
        raise ValueError("Invalid TRON address")
    payload, checksum = decoded[:-4], decoded[-4:]
    expected = hashlib.sha256(hashlib.sha256(payload).digest()).digest()[:4]
    if not hmac.compare_digest(checksum, expected) or len(payload) != 21 or payload[0] != 0x41:
        raise ValueError("Invalid TRON address")
    return payload


def tron_address_to_hex(address):
    return _base58_decode(address).hex()


def _tron_hex_address(address):
    if address.startswith("T"):
        return tron_address_to_hex(address)
    value = address.removeprefix("0x")
    if len(value) != 42 or not value.lower().startswith("41"):
        raise ValueError("Expected a TRON Base58Check or hex address")
    return value.lower()


def generate_tron_wallet():
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric import ec

    private_key = ec.generate_private_key(ec.SECP256K1())
    private_number = private_key.private_numbers().private_value
    private_hex = f"{private_number:064x}"
    public_key = private_key.public_key().public_bytes(
        serialization.Encoding.X962,
        serialization.PublicFormat.UncompressedPoint,
    )
    digest = keccak.new(digest_bits=256, data=public_key[1:]).digest()
    address_payload = b"\x41" + digest[-20:]
    checksum = hashlib.sha256(hashlib.sha256(address_payload).digest()).digest()[:4]
    return _base58_encode(address_payload + checksum), private_hex


def ensure_wallet(user):
    wallet = Wallet.objects.filter(user=user).first()
    if wallet:
        return wallet, False
    address, private_key = generate_tron_wallet()
    try:
        with transaction.atomic():
            wallet = Wallet.objects.create(
                user=user,
                address=address,
                encrypted_private_key=encrypt_private_key(private_key),
            )
        return wallet, True
    except IntegrityError:
        return Wallet.objects.get(user=user), False


def _trongrid_headers():
    headers = {"Accept": "application/json", "User-Agent": "CineVest/1.0"}
    api_key = getattr(settings, "TRONGRID_API_KEY", "")
    if api_key:
        headers["TRON-PRO-API-KEY"] = api_key
    return headers


def _trongrid_url(path):
    base = getattr(settings, "TRONGRID_BASE_URL", "https://api.trongrid.io").rstrip("/")
    return f"{base}/{path.lstrip('/')}"


def _request_json(url, *, method="GET", body=None, timeout=15):
    headers = _trongrid_headers()
    data = None
    if body is not None:
        data = json.dumps(body).encode("utf-8")
        headers["Content-Type"] = "application/json"
    request = Request(url, data=data, headers=headers, method=method)
    try:
        with urlopen(request, timeout=timeout) as response:
            return json.loads(response.read().decode("utf-8"))
    except (HTTPError, URLError, TimeoutError, json.JSONDecodeError) as exc:
        raise RuntimeError(f"تعذر الاتصال بخدمة TronGrid: {exc}") from exc


def _get_trc20_transfers(wallet):
    if not getattr(settings, "TRONGRID_API_KEY", ""):
        raise ImproperlyConfigured("أضف TRONGRID_API_KEY إلى متغيرات البيئة لمزامنة إيداعات TRON.")
    query = urlencode({
        "only_confirmed": "true",
        "limit": "200",
        "contract_address": getattr(settings, "TRON_USDT_CONTRACT", "TR7NHqjeKQxGTCi8q8ZY4pL8otSzgjLj6t"),
        "order_by": "block_timestamp,desc",
    })
    url = _trongrid_url(f"/v1/accounts/{wallet.address}/transactions/trc20?{query}")
    trusted_host = urlparse(getattr(settings, "TRONGRID_BASE_URL", "https://api.trongrid.io")).netloc
    pages = 0
    while url and pages < 20:
        if urlparse(url).netloc != trusted_host:
            raise RuntimeError("أعاد TronGrid رابط صفحة خارج الخدمة المحددة.")
        payload = _request_json(url)
        yield from payload.get("data", [])
        url = (payload.get("meta") or {}).get("links", {}).get("next")
        if url and url.startswith("/"):
            url = _trongrid_url(url)
        pages += 1


def _record_incoming_transfer(wallet, transfer):
    configured_contract = getattr(settings, "TRON_USDT_CONTRACT", "TR7NHqjeKQxGTCi8q8ZY4pL8otSzgjLj6t").lower()
    token = transfer.get("token_info") or {}
    contract = (token.get("address") or transfer.get("contract_address") or "").lower()
    recipient = (transfer.get("to") or "").lower()
    if recipient != wallet.address.lower() or contract != configured_contract:
        return False
    transaction_id = transfer.get("transaction_id") or transfer.get("transactionId")
    try:
        raw_value = int(transfer.get("value", "0"))
        decimals = int(token.get("decimals", USDT_DECIMALS))
        timestamp = int(transfer.get("block_timestamp", 0))
    except (TypeError, ValueError):
        return False
    if not transaction_id or raw_value <= 0 or not 0 <= decimals <= 18:
        return False
    amount = (Decimal(raw_value) / (Decimal(10) ** decimals)).quantize(Decimal("0.000001"))
    occurred_at = datetime.fromtimestamp(timestamp / 1000, tz=datetime_timezone.utc) if timestamp else timezone.now()
    from .services import approve_deposit, deposit_status_for_amount

    try:
        with transaction.atomic():
            deposit, created = Deposit.objects.get_or_create(
                transaction_id=transaction_id,
                defaults={
                    "user": wallet.user,
                    "wallet": wallet,
                    "amount": amount,
                    "reference": transaction_id,
                    "source": Deposit.Source.TRON,
                    "status": deposit_status_for_amount(amount),
                    "occurred_at": occurred_at,
                },
            )
            if created and deposit.status == Deposit.Status.PENDING:
                approve_deposit(deposit.pk)
            return created
    except IntegrityError:
        return False


def _trc20_balance(wallet):
    contract_hex = _tron_hex_address(getattr(settings, "TRON_USDT_CONTRACT", "TR7NHqjeKQxGTCi8q8ZY4pL8otSzgjLj6t"))
    owner_hex = _tron_hex_address(wallet.address)
    parameter = owner_hex[2:].rjust(64, "0")
    payload = _request_json(
        _trongrid_url("/wallet/triggerconstantcontract"),
        method="POST",
        body={
            "owner_address": owner_hex,
            "contract_address": contract_hex,
            "function_selector": "balanceOf(address)",
            "parameter": parameter,
            "visible": False,
        },
    )
    if payload.get("result", {}).get("result") is False:
        raise RuntimeError(payload.get("result", {}).get("message", "تعذر قراءة رصيد USDT"))
    result = payload.get("constant_result") or []
    if not result:
        return Decimal("0")
    return (Decimal(int(result[0], 16)) / (Decimal(10) ** USDT_DECIMALS)).quantize(Decimal("0.000001"))


def sync_wallet(wallet):
    imported = 0
    for transfer in _get_trc20_transfers(wallet):
        imported += int(_record_incoming_transfer(wallet, transfer))
    wallet.usdt_balance = _trc20_balance(wallet)
    wallet.balance_checked_at = timezone.now()
    wallet.save(update_fields=("usdt_balance", "balance_checked_at"))
    return imported


def sync_all_wallets():
    if not getattr(settings, "TRONGRID_API_KEY", ""):
        raise ImproperlyConfigured("أضف TRONGRID_API_KEY إلى متغيرات البيئة لمزامنة إيداعات TRON.")
    imported = 0
    updated = 0
    errors = []
    for wallet in Wallet.objects.select_related("user").order_by("pk"):
        try:
            imported += sync_wallet(wallet)
            updated += 1
        except Exception as exc:
            errors.append(f"{wallet.user.phone}: {exc}")
    return {"imported": imported, "updated": updated, "errors": errors}
