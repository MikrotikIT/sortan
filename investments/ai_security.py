import base64
import hashlib
import hmac

from cryptography.fernet import Fernet, InvalidToken
from django.conf import settings
from django.core.exceptions import ImproperlyConfigured


def _derived_fernet():
    digest = hmac.new(
        settings.SECRET_KEY.encode("utf-8"),
        b"Kodi TV-openrouter-api-key-v1",
        hashlib.sha256,
    ).digest()
    return Fernet(base64.urlsafe_b64encode(digest))


def _fernet():
    configured_key = getattr(settings, "OPENROUTER_ENCRYPTION_KEY", "")
    if not configured_key:
        return _derived_fernet()
    try:
        return Fernet(configured_key.encode("ascii"))
    except (TypeError, ValueError) as exc:
        raise ImproperlyConfigured(
            "OPENROUTER_ENCRYPTION_KEY must be a Fernet key generated by Fernet.generate_key()."
        ) from exc


def encrypt_openrouter_api_key(api_key):
    try:
        token = _fernet().encrypt(api_key.encode("utf-8"))
    except (UnicodeEncodeError, TypeError) as exc:
        raise ImproperlyConfigured("OpenRouter API key must be valid text.") from exc
    return token.decode("ascii")


def decrypt_openrouter_api_key(encrypted_api_key):
    try:
        token = encrypted_api_key.encode("ascii")
        decryptors = [_fernet()]
        if getattr(settings, "OPENROUTER_ENCRYPTION_KEY", ""):
            decryptors.append(_derived_fernet())
        for decryptor in decryptors:
            try:
                return decryptor.decrypt(token).decode("utf-8")
            except InvalidToken:
                continue
        raise InvalidToken
    except (InvalidToken, UnicodeDecodeError, UnicodeEncodeError, ValueError) as exc:
        raise ImproperlyConfigured(
            "تعذر فك تشفير مفتاح OpenRouter. تحقق من ثبات OPENROUTER_ENCRYPTION_KEY وDjango SECRET_KEY."
        ) from exc
